// Converts web/public/img/<slot>.jpg|png into AVIF + WebP + JPG at several widths
// (<slot>-<w>.<ext>) and writes src/lib/images.js so <Picture> uses them.
// Run: npm run images -w @fairswitch/web   (also runs before every build)
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, parse } from 'node:path';
import sharp from 'sharp';

const DIR = new URL('../public/img/', import.meta.url).pathname;
const OUT = new URL('../src/lib/images.js', import.meta.url).pathname;
const WIDTHS = [640, 1080, 1600, 2400];

const sources = readdirSync(DIR).filter((f) => /^[a-z0-9-]+\.(jpe?g|png)$/i.test(f) && !/-\d+\.(jpe?g|png)$/i.test(f));
const manifest = {};
for (const f of sources) {
  const slot = parse(f).name;
  const img = sharp(join(DIR, f));
  const { width, height } = await img.metadata();
  const widths = WIDTHS.filter((w) => w <= width);
  if (!widths.length) widths.push(width);
  for (const w of widths) {
    const base = join(DIR, `${slot}-${w}`);
    if (!existsSync(`${base}.avif`)) await sharp(join(DIR, f)).resize({ width: w }).avif({ quality: 55 }).toFile(`${base}.avif`);
    if (!existsSync(`${base}.webp`)) await sharp(join(DIR, f)).resize({ width: w }).webp({ quality: 74 }).toFile(`${base}.webp`);
    if (!existsSync(`${base}.jpg`)) await sharp(join(DIR, f)).resize({ width: w }).jpeg({ quality: 80, mozjpeg: true }).toFile(`${base}.jpg`);
  }
  manifest[slot] = { widths, w: width, h: height };
  console.log(`${slot}: ${width}×${height} → ${widths.join(', ')}`);
}
writeFileSync(OUT, `// Generated by scripts/images.js — do not edit.\nexport const IMAGES = ${JSON.stringify(manifest, null, 2)};\n`);
console.log(`${Object.keys(manifest).length} image slot(s) → src/lib/images.js`);
